/**
 * Idle animations ("fidgets") for characters standing still.
 *
 * Everyone blinks every few seconds (sometimes twice). On top of that,
 * characters perform an occasional fidget:
 * - lookAtCamera: turn to face the viewer for a moment (with a blink)
 * - checkWrist: raise a forearm as if checking a wrist gadget
 * - sigh: settle the upper body by a pixel
 *
 * NPCs fidget on their own every few seconds; the player only starts after
 * standing still for a while. Timing comes from a seeded random generator,
 * so each character has its own rhythm and tests are repeatable.
 *
 * No runtime dependencies, so it can be unit-tested in Node.
 */

/** Frames the idle animation shows (all generated by the sprite compositor). */
export type IdleFrame = "idle" | "blink" | "sigh" | "talk3";

export interface IdleState {
  frame: IdleFrame;
  /** True while the character briefly turns to face the viewer. */
  faceCamera: boolean;
}

export type Fidget = "lookAtCamera" | "checkWrist" | "sigh";

export interface IdleTiming {
  /** Delay before the first fidget after standing still, [min, max] ms. */
  firstFidgetMs: [number, number];
  /** Gap between fidgets, [min, max] ms. */
  fidgetGapMs: [number, number];
}

/** The player fidgets only after standing still for ~7s. */
export const PLAYER_IDLE: IdleTiming = {
  firstFidgetMs: [7000, 7500],
  fidgetGapMs: [8000, 14000],
};

/** NPCs fidget on their own every few seconds. */
export const NPC_IDLE: IdleTiming = {
  firstFidgetMs: [1500, 6000],
  fidgetGapMs: [5000, 12000],
};

export const FIDGET_LENGTH_MS: Record<Fidget, number> = {
  lookAtCamera: 1800,
  checkWrist: 1500,
  sigh: 900,
};
const FIDGETS: Fidget[] = ["lookAtCamera", "checkWrist", "sigh"];

export const BLINK_MS = 140;
const BLINK_GAP_MS: [number, number] = [2500, 6000];
const DOUBLE_BLINK_CHANCE = 0.2;

/** Small seeded PRNG (mulberry32). */
export function seededRandom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A stable seed from a string, e.g. an NPC's id. */
export function seedFrom(text: string): number {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h = Math.imul(h ^ text.charCodeAt(i), 16777619);
  }
  return h >>> 0;
}

/**
 * Tracks one character's idle animation. Call reset() when they start
 * standing still, then frameAt(now) every frame with increasing times.
 */
export class IdleAnimator {
  private readonly random: () => number;
  private nextBlink = 0;
  private blinkEnds = -Infinity;
  private secondBlinkAt: number | null = null;
  private nextFidget = 0;
  private fidget: { type: Fidget; ends: number } | null = null;
  private lastFidget: Fidget | null = null;
  private readonly timing: IdleTiming;

  constructor(timing: IdleTiming, seed: number) {
    this.timing = timing;
    this.random = seededRandom(seed);
  }

  /** The character has just started standing still. */
  reset(now: number): void {
    this.fidget = null;
    this.blinkEnds = -Infinity;
    this.secondBlinkAt = null;
    this.nextBlink = now + this.between([1500, 4000]);
    this.nextFidget = now + this.between(this.timing.firstFidgetMs);
  }

  /** What to show at time `now` (ms). */
  frameAt(now: number): IdleState {
    // Fidgets
    if (this.fidget && now >= this.fidget.ends) {
      this.fidget = null;
      this.nextFidget = now + this.between(this.timing.fidgetGapMs);
    }
    if (!this.fidget && now >= this.nextFidget) {
      const type = this.pickFidget();
      this.fidget = { type, ends: now + FIDGET_LENGTH_MS[type] };
      this.lastFidget = type;
      // Blink partway through looking at the viewer.
      if (type === "lookAtCamera") this.nextBlink = now + 700;
    }

    // Blinks
    if (this.secondBlinkAt !== null && now >= this.secondBlinkAt) {
      this.blinkEnds = this.secondBlinkAt + BLINK_MS;
      this.secondBlinkAt = null;
    }
    if (now >= this.nextBlink) {
      this.blinkEnds = this.nextBlink + BLINK_MS;
      if (this.random() < DOUBLE_BLINK_CHANCE) {
        this.secondBlinkAt = this.nextBlink + BLINK_MS + 120;
      }
      this.nextBlink = now + this.between(BLINK_GAP_MS);
    }
    const blinking = now < this.blinkEnds;

    switch (this.fidget?.type) {
      case "checkWrist":
        return { frame: "talk3", faceCamera: false };
      case "sigh":
        return { frame: "sigh", faceCamera: false };
      case "lookAtCamera":
        return { frame: blinking ? "blink" : "idle", faceCamera: true };
      default:
        return { frame: blinking ? "blink" : "idle", faceCamera: false };
    }
  }

  private between([min, max]: [number, number]): number {
    return min + this.random() * (max - min);
  }

  /** A random fidget, never the same one twice in a row. */
  private pickFidget(): Fidget {
    const options = FIDGETS.filter((f) => f !== this.lastFidget);
    return options[Math.floor(this.random() * options.length)];
  }
}
